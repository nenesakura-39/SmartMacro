    /// <summary>
    /// Hides (or un-hides) one of our own windows from screen captures, so OCR reads whatever is behind it.
    /// Best effort: needs Windows 10 2004+ and the desktop compositor.
    /// </summary>
    public static void SetExcludedFromCapture(System.Windows.Window window, bool excluded)
    {
        var hwnd = new System.Windows.Interop.WindowInteropHelper(window).Handle;
        if (hwnd != IntPtr.Zero) SetWindowDisplayAffinity(hwnd, excluded ? WDA_EXCLUDEFROMCAPTURE : WDA_NONE);
    }

    private const uint LWA_ALPHA = 0x00000002;

    [DllImport("user32.dll", SetLastError = true)]
